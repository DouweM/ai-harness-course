"""Build part2/NN-*.html from part2/_src/NN-*.html.

The sources hold each chapter's body. This script pulls code snippets from code/part2/ (between
`# --8<-- [start:name]` and `# --8<-- [end:name]` markers) and recorded outputs from code/part2/expected/, so what a
page shows is what verify.py ran. No build step is needed to view the pages; run this after changing a source or the
code:

    python3 part2/_build.py

Placeholders in a source:
    {{code FILE NAME "label"}}      a code card with the snippet; label defaults to the file name
    {{out MODULE [FIRST-LAST]}}     a card with that module's recorded output (optionally a line range, 1-based)
"""

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'part2' / '_src'
CODE = ROOT / 'code' / 'part2'
FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600'
    '&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400&display=swap">'
)


def snippet(file: str, name: str) -> str:
    text = (CODE / file).read_text()
    m = re.search(rf'# --8<-- \[start:{re.escape(name)}\]\n(.*?)# --8<-- \[end:{re.escape(name)}\]', text, re.S)
    if not m:
        raise SystemExit(f'no snippet {name!r} in {file}')
    return m.group(1).rstrip('\n')


def code_card(m: re.Match[str]) -> str:
    file, name, label, keys = m.group(1), m.group(2), m.group(3) or f'code/part2/{m.group(1)}', m.group(4)
    body = snippet(file, name)
    if keys:  # a focus card: only the lines matching `keys` show until the reader asks for all of them
        hits = [i for i, line in enumerate(body.split('\n')) if re.search(keys, line)]
        if not hits:
            raise SystemExit(f'{file}:{name}: no line matches {keys!r}')
        return (
            f'<div class="code focus" data-keys="{",".join(map(str, hits))}" data-run="uv run code/part2/{file}">'
            f'<div class="code-head"><span class="file">{html.escape(label)}</span>'
            f'<button class="copy" type="button">Copy</button></div>'
            f'<pre data-lang="py" data-hl="1">{html.escape(body)}</pre></div>'
        )
    long = ' long' if body.count('\n') > 22 else ''
    return (
        f'<div class="code{long}" data-run="uv run code/part2/{file}">'
        f'<div class="code-head"><span class="file">{html.escape(label)}</span>'
        f'<button class="copy" type="button">Copy</button></div>'
        f'<pre data-lang="py">{html.escape(body)}</pre></div>'
    )


def out_card(m: re.Match[str]) -> str:
    module, span = m.group(1), m.group(2)
    lines = (CODE / 'expected' / f'{module}.txt').read_text().rstrip('\n').split('\n')
    if span:
        first, last = (int(x) for x in span.split('-'))
        lines = lines[first - 1 : last]
    return (
        '<div class="code out"><div class="code-head"><span class="file">// output, recorded by verify.py</span></div>'
        f'<pre>{html.escape(chr(10).join(lines))}</pre></div>'
    )


def out_inline(m: re.Match[str]) -> str:
    lines = (CODE / 'expected' / f'{m.group(1)}.txt').read_text().split('\n')
    return html.escape(lines[int(m.group(2)) - 1])


def build(src: Path) -> None:
    text = src.read_text()
    meta, body = text.split('\n---\n', 1)
    fields = dict(line.split(': ', 1) for line in meta.strip().splitlines())
    body = re.sub(r'\{\{code (\S+) (\S+)(?: "([^"]*)")?(?: keys="([^"]*)")?\}\}', code_card, body)
    body = re.sub(r'\{\{out (\S+)(?: (\d+-\d+))?\}\}', out_card, body)
    body = re.sub(r'\{\{out-inline (\S+) (\d+)\}\}', out_inline, body)
    extra = ''
    if '{{composer-data}}' in body:
        data = (CODE / 'expected' / 'composer.json').read_text()
        body = body.replace('{{composer-data}}', '')
        extra = f'<script type="application/json" id="composer-data">{data}</script>\n'
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{fields['title']} · Harness engineering</title>
<meta name="description" content="{html.escape(fields['description'])}">
{FONTS}
<link rel="stylesheet" href="../assets/theme.css">
<link rel="stylesheet" href="part2.css">
</head>
<body data-page="chapter" data-title="{html.escape(fields['title'])}" data-part="2" data-n="{fields['n']}" data-runtime="{fields['runtime']}">
<!-- Generated by part2/_build.py from part2/_src/{src.name}: edit the source, then rebuild. -->

<header class="topbar" data-auto></header>

<main>
{body.strip()}
</main>

<footer><div class="wrap"><p>Every snippet runs offline on pydantic-ai 2.68.0 and pydantic-ai-harness 0.68.0: <code>uv run code/part2/verify.py</code>.</p></div></footer>

<script src="../assets/course.js"></script>
{extra}<script src="part2.js"></script>
</body>
</html>
'''
    if '\u2014' in page:
        raise SystemExit(f'{src.name}: em dash')
    (ROOT / 'part2' / src.name).write_text(page)
    print('built', src.name)


if __name__ == '__main__':
    for old in (ROOT / 'part2').glob('0*.html'):
        if not (SRC / old.name).exists():
            old.unlink()
            print('removed', old.name)
    for src in sorted(SRC.glob('*.html')):
        build(src)
