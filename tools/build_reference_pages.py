"""Build reference/NAME.html from reference/_src/NAME.html (hand-written reference pages, not the generated gallery).

Like part2/_build.py: snippets come from code/reference/composing_harnesses.py (between `# --8<-- [start:name]` and
`# --8<-- [end:name]`) and outputs from code/reference/expected/, so what the page shows is what verify.py ran.

    python3 tools/build_reference_pages.py

Placeholders in a source:
    {{code NAME "label"}}   a code card with that snippet
    {{out FIRST-LAST}}      a card with those lines (1-based) of the recorded output
"""

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'reference' / '_src'
CODE = ROOT / 'code' / 'reference'
MODULE = 'composing_harnesses'
FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600'
    '&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400&display=swap">'
)
STYLE = '''<style>
  .toc-mini { margin: 14px 0 8px; padding-left: 1.4em; max-width: 72ch; }
  .toc-mini li { margin: 0; }
  .toc-mini li + li { margin-top: 0; }
  .toc-mini a { display: inline-block; padding: 4px 0; min-height: 0; }
  main section > section { margin: 44px 0; }
  .code.out pre { background: var(--bg); }
  .code.out .code-head .file { color: var(--model); }
  .tbl-wrap { overflow-x: auto; margin: 18px 0; border: 1px solid var(--border); border-radius: var(--radius-card); background: var(--surface); }
  table.tbl { width: 100%; border-collapse: collapse; font-size: .9375rem; }
  .tbl th, .tbl td { text-align: left; vertical-align: top; padding: 9px 12px; border-bottom: 1px solid var(--border); }
  .tbl th { font: 600 .8125rem var(--font-mono); color: var(--eyebrow); background: var(--bg-alt); }
  .tbl tr:last-child td { border-bottom: 0; }
  .tbl td:first-child { font-weight: 600; min-width: 9em; }
  .tbl code { font-size: .8125rem; overflow-wrap: anywhere; }
  @media (max-width: 640px) {
    table.tbl, .tbl tbody, .tbl tr, .tbl td { display: block; width: 100%; }
    .tbl thead { display: none; }
    .tbl tr { border-bottom: 1px solid var(--border); padding: 6px 0; }
    .tbl td { border: 0; padding: 3px 12px; }
  }
</style>'''


def snippet(name: str) -> str:
    text = (CODE / f'{MODULE}.py').read_text()
    m = re.search(rf'# --8<-- \[start:{re.escape(name)}\]\n(.*?)# --8<-- \[end:{re.escape(name)}\]', text, re.S)
    if not m:
        raise SystemExit(f'no snippet {name!r} in {MODULE}.py')
    return m.group(1).rstrip('\n')


def code_card(m: re.Match[str]) -> str:
    body = snippet(m.group(1))
    long = ' long' if body.count('\n') > 45 else ''
    return (
        f'<div class="code{long}" data-run="uv run code/reference/{MODULE}.py">'
        f'<div class="code-head"><span class="file">{html.escape(m.group(2))}</span>'
        f'<button class="copy" type="button">Copy</button></div>'
        f'<pre data-lang="py">{html.escape(body)}</pre></div>'
    )


def out_card(m: re.Match[str]) -> str:
    lines = (CODE / 'expected' / f'{MODULE}.txt').read_text().rstrip('\n').split('\n')
    first, last = (int(x) for x in m.group(1).split('-'))
    return (
        '<div class="code out"><div class="code-head"><span class="file">// output, recorded by verify.py</span></div>'
        f'<pre>{html.escape(chr(10).join(lines[first - 1 : last]))}</pre></div>'
    )


def build(src: Path) -> None:
    meta, body = src.read_text().split('\n---\n', 1)
    fields = dict(line.split(': ', 1) for line in meta.strip().splitlines())
    body = re.sub(r'\{\{code (\S+) "([^"]*)"\}\}', code_card, body)
    body = re.sub(r'\{\{out (\d+-\d+)\}\}', out_card, body)
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(fields['title'])} · Harness engineering</title>
<meta name="description" content="{html.escape(fields['description'])}">
{FONTS}
<link rel="stylesheet" href="../assets/theme.css">
{STYLE}
</head>
<body data-page="reference" data-path="reference/{src.name}">
<!-- Generated by tools/build_reference_pages.py from reference/_src/{src.name}: edit the source, then rebuild. -->
<header class="topbar" data-auto></header>
<main>
{body.strip()}
</main>
<footer><div class="wrap"><p>Every snippet runs offline on pydantic-ai 2.68.0 and pydantic-ai-harness 0.68.0: <code>uv run code/reference/verify.py</code>.</p></div></footer>
<script src="../assets/course.js"></script>
</body>
</html>
'''
    if '\u2014' in page:
        raise SystemExit(f'{src.name}: em dash')
    (ROOT / 'reference' / src.name).write_text(page)
    print('built', src.name)


if __name__ == '__main__':
    for src in sorted(SRC.glob('*.html')):
        build(src)
